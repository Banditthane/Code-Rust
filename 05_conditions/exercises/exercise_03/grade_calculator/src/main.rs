fn main() {
    let score = 75;

    if score >= 80 {
        println!("Grade: A");
    } else if score >= 70 {
        println!("Grade: B");
    } else if score >= 60 {
        println!("Grade: C");
    } else if score >= 50 {
        println!("Grade: D");
    } else {
        println!("Grade: F");
    }
}
